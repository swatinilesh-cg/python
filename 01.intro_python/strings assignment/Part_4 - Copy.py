# --- Task 4: Positive Indexing ---
word = "Programming"
print("First character:", word[0])
print("Second character:", word[1])
print("Fifth character:", word[4])
print("Last character:", word[10]) # or word[-1]

# --- Task 5: Negative Indexing ---
print("Last character:", word[-1])
print("Second-last character:", word[-2])
print("Third-last character:", word[-3])
print("First character:", word[-11])

# --- Task 6: Indexing Challenge ---
full_name = "Jane Doe"
print("First character:", full_name[0])
print("Last character:", full_name[-1])
print("First character of last name:", full_name[5]) # Index 5 is 'D'